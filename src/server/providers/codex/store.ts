import { DatabaseSync } from 'node:sqlite';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { assertReadable } from '../../paths.ts';
import type { PathPolicy } from '../../paths.ts';

/**
 * Read-only access to Codex's SQLite logs, for the one thing the rollouts do
 * not say: which process runs which thread.
 *
 * Codex keeps other indexes beside it (`threads` in `state_5.sqlite`, the
 * decoded items in `thread_history_1.sqlite`). They were read here once, and
 * nothing used them: the rollouts carry what the city shows, so those files
 * are no longer opened nor on the allow-list.
 *
 * `node:sqlite` is built into Node 22: reading them adds no dependencies.
 */

/** `immutable=1` creates no side files and also works on WAL-mode DBs. */
function openReadOnly(file: string, policy: PathPolicy): DatabaseSync | null {
  try {
    assertReadable(file, policy);
  } catch {
    return null;
  }
  if (!fs.existsSync(file)) return null;
  try {
    return new DatabaseSync(`file:${file}?immutable=1`, { readOnly: true });
  } catch {
    return null;
  }
}

function str(v: unknown): string | null {
  return typeof v === 'string' && v.length > 0 ? v : null;
}

function int(v: unknown): number {
  return typeof v === 'number' && Number.isFinite(v) ? v : 0;
}

export class CodexStore {
  #policy: PathPolicy;
  #dir: string;

  constructor(codexDir: string, policy: PathPolicy) {
    this.#dir = codexDir;
    this.#policy = policy;
  }

  /** Whether Codex is installed: its thread index exists. Checked, never opened. */
  get available(): boolean {
    return fs.existsSync(path.join(this.#dir, 'state_5.sqlite'));
  }

  /**
   * PID per thread, from the logs.
   *
   * Codex does not publish a registry of live sessions the way Claude Code
   * does, and the files in `thread-writer-locks/` are a false lead: they are
   * 0 bytes and survive the process's death (verified). The only real hook is
   * `process_uuid`, in the form `pid:<PID>:<uuid>`.
   */
  readThreadPids(): Map<string, { pid: number; lastTs: number }> {
    const out = new Map<string, { pid: number; lastTs: number }>();
    const db = openReadOnly(path.join(this.#dir, 'logs_2.sqlite'), this.#policy);
    if (!db) return out;
    try {
      const rows = db
        .prepare(
          `SELECT thread_id, process_uuid, MAX(ts) AS last_ts
             FROM logs
            WHERE thread_id IS NOT NULL AND process_uuid IS NOT NULL
            GROUP BY thread_id, process_uuid`,
        )
        .all() as Record<string, unknown>[];

      for (const r of rows) {
        const threadId = str(r['thread_id']);
        const uuid = str(r['process_uuid']);
        if (!threadId || !uuid) continue;
        const parts = uuid.split(':');
        if (parts.length < 2 || parts[0] !== 'pid') continue;
        const pid = Number(parts[1]);
        if (!Number.isInteger(pid) || pid <= 1) continue;
        const lastTs = int(r['last_ts']) * 1000; // the logs are in seconds
        const prev = out.get(threadId);
        if (!prev || lastTs > prev.lastTs) out.set(threadId, { pid, lastTs });
      }
      return out;
    } catch {
      return out;
    } finally {
      db.close();
    }
  }

  /**
   * Readable name per thread, from `session_index.jsonl`.
   *
   * The file is an append-only log of renames: the same id can have several
   * lines, and the LAST one wins. The name is generated by the model, like
   * Claude Code's `ai-title`, so it follows the same `--no-titles` flag.
   */
  readThreadNames(): Map<string, string> {
    const out = new Map<string, string>();
    const file = path.join(this.#dir, 'session_index.jsonl');
    try {
      assertReadable(file, this.#policy);
    } catch {
      return out;
    }
    let text: string;
    try {
      text = fs.readFileSync(file, 'utf8');
    } catch {
      return out;
    }
    for (const line of text.split('\n')) {
      if (line.length === 0 || line.length > 8192) continue;
      try {
        const rec = JSON.parse(line) as Record<string, unknown>;
        const id = str(rec['id']);
        const name = str(rec['thread_name']);
        if (id && name) out.set(id, name.slice(0, 64));
      } catch {
        // malformed line: carry on
      }
    }
    return out;
  }

  /**
   * Projects declared in `config.toml`, sections `[projects."<path>"]`.
   * The `projects` table in SQLite exists but is empty, so this is the only
   * list of declared projects that Codex keeps on disk.
   */
  readDeclaredProjects(): string[] {
    const file = path.join(this.#dir, 'config.toml');
    try {
      assertReadable(file, this.#policy);
    } catch {
      return [];
    }
    let text: string;
    try {
      text = fs.readFileSync(file, 'utf8');
    } catch {
      return [];
    }
    // A full TOML parser would be a dependency just to read one line.
    const out: string[] = [];
    const re = /^\s*\[projects\."([^"]+)"\]/gm;
    let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) {
      const p = m[1];
      if (p && path.isAbsolute(p)) out.push(p);
    }
    return out;
  }
}
