import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';

/**
 * The bridge to Claude Code's statusline.
 *
 * It exists for one reason only: the consumed quota -- `rate_limits.five_hour`
 * and `seven_day` -- is NOT in any file or any command. Claude Code passes it
 * on the stdin of the statusline command with every response, and that is the
 * only place it exists on this machine.
 *
 * The bridge does not replace your statusline: it wraps it. It receives the
 * JSON, saves a copy under `~/.towerglow/`, and then passes the exact same
 * input to the command that was there before, relaying its output word for
 * word. If your script breaks or is missing, the bar stays empty but the
 * session is unaffected: the statusline cannot block Claude Code.
 *
 * It is opt-in, with a backup and an uninstall that restores the file as it
 * was.
 */

/** Marker to recognize what we installed ourselves. */
const MARK = 'towerglow-statusline-bridge';

export interface StatuslineStatus {
  installed: boolean;
  /** The command we wrap, if there was one. */
  wrapped: string | null;
  bridgePath: string;
  dataPath: string;
}

interface Manifest {
  version: number;
  /** The original command, so it can be put back identical. */
  previous: unknown;
  /** Was the `statusLine` key there before us? If not, it must be removed entirely. */
  hadStatusLine: boolean;
  backupPath: string;
  sha256Before: string;
  installedAt: number;
}

export interface StatuslinePaths {
  claudeDir: string;
  stateDir: string;
}

const MANIFEST_VERSION = 1;

function settingsPath(p: StatuslinePaths): string {
  return path.join(p.claudeDir, 'settings.json');
}

function bridgePath(p: StatuslinePaths): string {
  return path.join(p.stateDir, 'statusline-bridge.sh');
}

function manifestPath(p: StatuslinePaths): string {
  return path.join(p.stateDir, 'statusline-manifest.json');
}

/** Where the bridge drops what it receives. */
export function dataPath(stateDir: string): string {
  return path.join(stateDir, 'statusline', 'latest.json');
}

/** Where the bridge drops one copy per session. */
export function sessionsPath(stateDir: string): string {
  return path.join(stateDir, 'statusline', 'sessions');
}

function readJson(file: string): Record<string, unknown> | null {
  try {
    const raw = fs.readFileSync(file, 'utf8');
    const parsed: unknown = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? (parsed as Record<string, unknown>) : null;
  } catch {
    return null;
  }
}

function sha(file: string): string {
  try {
    return createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  } catch {
    return '';
  }
}

/**
 * The original command made executable inside the bridge.
 *
 * Claude Code accepts two forms: a string, or an object with `command`.
 * Whichever it is, what comes out must be written ONCE into the bridge and
 * never reassembled from pieces: it is the user's text, and concatenating it
 * would be the most direct way to break their bar.
 */
function commandOf(statusLine: unknown): string | null {
  if (typeof statusLine === 'string') return statusLine;
  if (statusLine && typeof statusLine === 'object') {
    const cmd = (statusLine as Record<string, unknown>)['command'];
    if (typeof cmd === 'string' && cmd.length > 0) return cmd;
  }
  return null;
}

/** The bridge's text, with the command to wrap inside it. */
function bridgeScript(inner: string | null, dataFile: string): string {
  const runInner = inner
    ? `# The statusline you had before, with the same input and the same output.\nprintf '%s' "$payload" | ${inner}\n`
    : '# There was no statusline before this one: nothing to show again.\n';

  return `#!/bin/bash
# ${MARK}
# Generated by: towerglow statusline install
# Remove it with: towerglow statusline uninstall
#
# Reads the JSON that Claude Code passes to the statusline, saves a copy, and
# then lets the statusline that was there before do its work. It decides
# nothing and cannot block the session: any error here is silent on purpose.

# Everything written here is readable only by you.
umask 077

payload=$(cat)

out=${JSON.stringify(path.dirname(dataFile))}
mkdir -p "$out/sessions" 2>/dev/null
if [ -n "$payload" ]; then
  printf '%s' "$payload" > "$out/latest.json.tmp" 2>/dev/null &&
    mv -f "$out/latest.json.tmp" ${JSON.stringify(dataFile)} 2>/dev/null

  # One copy per session: the context window belongs to each session, and
  # latest.json only tells the one that responded last. The id ends up in a
  # file name, so it only passes if it has the exact shape of an id.
  sid=$(printf '%s' "$payload" | grep -o '"session_id":"[^"]*"' | head -1 | cut -d'"' -f4)
  case "$sid" in
    ''|*[!0-9a-fA-F-]*) sid='' ;;
  esac
  if [ -n "$sid" ]; then
    printf '%s' "$payload" > "$out/sessions/$sid.json.tmp" 2>/dev/null &&
      mv -f "$out/sessions/$sid.json.tmp" "$out/sessions/$sid.json" 2>/dev/null
  fi
fi

${runInner}`;
}

export function statuslineStatus(p: StatuslinePaths): StatuslineStatus {
  const manifest = readJson(manifestPath(p)) as unknown as Manifest | null;
  const settings = readJson(settingsPath(p));
  const current = commandOf(settings?.['statusLine']);
  const bridge = bridgePath(p);
  return {
    /*
     * The FULL path, not the basename.
     *
     * The bridge is called `statusline-bridge.sh` in any state folder, so
     * with the basename a second copy of the tree -- different --state-dir,
     * same file name -- saw the other copy's bridge as installed and reasoned
     * on top of it: refreshBridge wrote it an orphan bridge, and a
     * `statusline install` from there would have saved the first copy's
     * bridge as the "previous command", or worse nothing, losing the user's
     * real statusline.
     */
    installed: current !== null && current.includes(bridge),
    wrapped: manifest ? commandOf(manifest.previous) : null,
    bridgePath: bridge,
    dataPath: dataPath(p.stateDir),
  };
}

export class StatuslineError extends Error {}

/**
 * Installs the bridge.
 *
 * A corrupted `settings.json` would cost the user far more than this function
 * is worth, hence the order: Backup, write to a temporary file, atomic rename, verification
 * re-read, and restore if the verification fails.
 */
export function installStatusline(p: StatuslinePaths): StatuslineStatus {
  const file = settingsPath(p);
  const existing = fs.existsSync(file);

  let settings: Record<string, unknown> = {};
  if (existing) {
    const parsed = readJson(file);
    if (!parsed) {
      throw new StatuslineError(
        `${file} is not valid JSON: leaving it untouched. Fix it and try again.`,
      );
    }
    settings = parsed;
  }

  const already = statuslineStatus(p);
  // Reinstalling must update, not wedge the bridge inside itself.
  const previous = already.installed
    ? (readJson(manifestPath(p)) as unknown as Manifest | null)?.previous ?? null
    : settings['statusLine'] ?? null;

  fs.mkdirSync(p.stateDir, { recursive: true, mode: 0o700 });
  const backup = path.join(p.stateDir, 'backups', `settings.${new Date().toISOString()}.json`);
  if (existing) {
    fs.mkdirSync(path.dirname(backup), { recursive: true, mode: 0o700 });
    fs.copyFileSync(file, backup);
  }

  const bridge = bridgePath(p);
  fs.writeFileSync(bridge, bridgeScript(commandOf(previous), dataPath(p.stateDir)), { mode: 0o700 });

  const manifest: Manifest = {
    version: MANIFEST_VERSION,
    previous,
    hadStatusLine: 'statusLine' in settings,
    backupPath: existing ? backup : '',
    sha256Before: existing ? sha(file) : '',
    installedAt: Date.now(),
  };

  const next = { ...settings, statusLine: { type: 'command', command: `bash ${bridge}` } };
  writeSettings(file, next, existing ? backup : null);
  fs.writeFileSync(manifestPath(p), JSON.stringify(manifest, null, 2) + '\n', { mode: 0o600 });

  return statuslineStatus(p);
}

/**
 * Rewrites the bridge with the current version, WITHOUT touching
 * `settings.json`.
 *
 * The bridge is our own file in `~/.towerglow`: when what it must save
 * changes, updating it does not require touching Claude Code's configuration
 * again, which keeps pointing to the same path.
 * Does nothing if the bridge is not installed.
 */
export function refreshBridge(p: StatuslinePaths): boolean {
  const status = statuslineStatus(p);
  if (!status.installed) return false;
  const manifest = readJson(manifestPath(p)) as unknown as Manifest | null;
  const inner = manifest ? commandOf(manifest.previous) : null;
  const next = bridgeScript(inner, dataPath(p.stateDir));
  try {
    if (fs.readFileSync(status.bridgePath, 'utf8') === next) return false;
  } catch {
    // missing: rewrite it
  }
  fs.writeFileSync(status.bridgePath, next, { mode: 0o700 });
  return true;
}

/** Puts `settings.json` back exactly as it was, and deletes the bridge. */
export function uninstallStatusline(p: StatuslinePaths): 'restored' | 'not-installed' {
  const file = settingsPath(p);
  const settings = readJson(file);
  const manifest = readJson(manifestPath(p)) as unknown as Manifest | null;

  /*
   * settings.json is touched only while it runs OUR bridge. It used to be
   * rewritten whatever it held: with no manifest the `statusLine` key was
   * deleted, so an uninstall from someone who never installed the bridge --
   * or who had since put a status line of their own -- took theirs away.
   */
  const ours = statuslineStatus(p).installed;
  if (settings && ours) {
    const next = { ...settings };
    if (manifest && manifest.hadStatusLine) next['statusLine'] = manifest.previous;
    else delete next['statusLine'];
    writeSettings(file, next, manifest?.backupPath || null);
  }

  for (const f of [bridgePath(p), manifestPath(p)]) {
    try {
      fs.unlinkSync(f);
    } catch {
      // already gone: uninstalling stays idempotent
    }
  }
  return settings && ours ? 'restored' : 'not-installed';
}

/**
 * Writes and RE-READS. If what comes back is not valid JSON the backup is
 * restored: it is the only way not to leave the user with a configuration
 * broken by our fault.
 */
function writeSettings(file: string, value: unknown, backup: string | null): void {
  const tmp = `${file}.towerglow.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(value, null, 2) + '\n', { mode: 0o600 });
  fs.renameSync(tmp, file);
  if (readJson(file)) return;

  if (backup && fs.existsSync(backup)) fs.copyFileSync(backup, file);
  throw new StatuslineError(`${file} unreadable after writing: restored from the backup.`);
}
